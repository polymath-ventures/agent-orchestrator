// Generates frontend/index.d.ts — the declaration entry the converter's prop
// extractor resolves (it looks for <pkgDir>/index.d.ts when package.json
// declares no `types` field, and only sees files under the types root, which
// for this layout is the package dir itself).
//
// Declarations are emitted to dist/decl rather than dist/types on purpose:
// findTypesRoot() would return dist/types and then index.d.ts, sitting at the
// package root, would fall outside the parsed tree and resolve to nothing —
// which is what left every component with `[key: string]: unknown`.
//
// Run from the repo root, after tsc emits into frontend/dist/decl.
import { readdirSync, writeFileSync } from "node:fs";

const UI_SRC = "frontend/src/renderer/components/ui";
const DECL = "./dist/decl/renderer/components/ui";

const mods = readdirSync(UI_SRC)
	.filter((f) => f.endsWith(".tsx") && !f.includes(".test."))
	.map((f) => f.replace(/\.tsx$/, ""))
	.sort();

const body =
	"// Generated by .design-sync/emit-types-barrel.mjs — do not edit.\n" +
	mods.map((m) => `export * from "${DECL}/${m}";`).join("\n") +
	"\n";

writeFileSync("frontend/index.d.ts", body);
console.log(`index.d.ts: ${mods.length} module(s)`);
